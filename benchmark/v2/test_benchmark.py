import json
from pathlib import Path
from tempfile import TemporaryDirectory
import unittest

from benchmark import grade, precheck, select_details


class BenchmarkTests(unittest.TestCase):
    def test_grades_last_list_and_reports_format_separately(self):
        response = 'First {"answer":["wrong"]}\n```json\n{"answer":["./papermark/pages\\\\api.ts","post   /api/x"]}\n```'
        result = grade(response, ["pages/api.ts", "POST /api/x"], "mfts/papermark")
        self.assertTrue(result["content_exact"])
        self.assertFalse(result["format_ok"])
        self.assertTrue(result["ambiguous"])
        self.assertEqual(result["f1"], 1)

    def test_partial_and_malformed_json(self):
        self.assertEqual(grade('{"answer":["A","A"]}', ["A", "B"], "repo")["f1"], 2 / 3)
        self.assertTrue(grade('{"answer":["A"]}', ["A"], "repo")["format_ok"])
        self.assertFalse(grade('{"answer":[null]}', ["A"], "repo")["content_exact"])

    def test_selection_prioritizes_an_explicit_area(self):
        with TemporaryDirectory() as root:
            root = Path(root)
            graph = root / ".neorion/graph"
            graph.mkdir(parents=True)
            (graph / "one.md").write_text("<!-- Generated by Neorion -->\n# components/chat\n")
            (graph / "two.md").write_text("<!-- Generated by Neorion -->\n# pages\n\nuseStream")
            self.assertEqual(select_details("Which components/chat/ files use useStream?", root)[0][0],
                             ".neorion/graph/one.md")

    def test_parent_scope_prioritizes_descendant_details(self):
        with TemporaryDirectory() as root:
            root = Path(root)
            graph = root / ".neorion/graph"
            graph.mkdir(parents=True)
            (graph / "features.md").write_text("<!-- Generated by Neorion -->\n# ee/features\n\nuseTeam")
            (graph / "+reverse-hooks.md").write_text("<!-- Generated by Neorion -->\n# Reverse usage: hooks\n\nuseTeam (177)")
            name, _ = select_details("Which files under ee/ declare 'use client' and call useTeam?", root)[0]
            self.assertEqual(Path(name).name, "features.md")

    def test_negated_layouts_do_not_win_and_matching_shard_does(self):
        with TemporaryDirectory() as root:
            root = Path(root)
            graph = root / ".neorion/graph"
            graph.mkdir(parents=True)
            for name, heading, body in (
                ("layout.md", "components/layouts", "layouts"),
                ("pages.md", "pages", "page URLs"),
                ("pages+2.md", "pages", "AccountHeader"),
                ("analytics.md", "components/analytics", "AccountHeader"),
                ("+reverse-renders.md", "Reverse usage: renders", "AccountHeader (2)"),
            ):
                (graph / name).write_text(f"<!-- Generated by Neorion -->\n# {heading}\n\n{body}")
            question = "Which page URLs render AccountHeader? Exclude layouts."
            chosen = [Path(file).name for file, _ in select_details(question, root)]
            self.assertEqual(chosen, ["+reverse-renders.md", "analytics.md", "pages+2.md"])

    def test_page_lookup_follows_a_render_edge_to_the_intermediate(self):
        with TemporaryDirectory() as root:
            root = Path(root)
            graph = root / ".neorion/graph"
            graph.mkdir(parents=True)
            for name, body in {
                "definition": "  target.tsx: ChartPanel",
                "table": "widgets/\n  table.tsx: AccountsTable | > ChartPanel",
                "page": "  index.tsx: Dashboard | route index.tsx=Dashboard | > widgets/table.tsx#AccountsTable",
                "layouts": "  shell.tsx: Shell | > ChartPanel[import]",
            }.items():
                (graph / f"{name}.md").write_text(f"<!-- Generated by Neorion -->\n# {name}\n\n{body}")
            question = "Which page URLs render ChartPanel directly or through one component? Exclude layouts."
            self.assertEqual([Path(file).stem for file, _ in select_details(question, root, limit=2)],
                             ["page", "table"])

    def test_normalizes_qualified_component_names_and_relative_urls(self):
        for response, expected, template in (
            ('{"answer":["components/analytics/links-table.tsx#LinksTable"]}', ["LinksTable"], 7),
            ('{"answer":["datarooms/[id]","/documents/[id]"]}', ["/datarooms/[id]", "/documents/[id]"], 10),
        ):
            with self.subTest(template=template):
                result = grade(response, expected, "mfts/papermark", template)
                self.assertTrue(result["format_ok"])
                self.assertTrue(result["content_exact"])
                self.assertEqual(result["f1"], 1)
                self.assertFalse(grade(response, expected, "mfts/papermark", 1)["content_exact"])

    def test_precheck_flags_exact_a_content(self):
        questions = [{"id": key, "repo": "repo", "answer": ["/yes"], "template": 10} for key in ("q1", "q2")]
        with TemporaryDirectory() as root:
            responses = Path(root) / "responses.jsonl"
            report = Path(root) / "screen.jsonl"
            rows = [{"id": item["id"], "condition": "A",
                     "response": json.dumps({"answer": ["yes" if item["id"] == "q1" else "no"]})}
                    for item in questions]
            responses.write_text("\n".join(map(json.dumps, rows)))
            precheck(questions, responses, report)
            self.assertEqual([json.loads(row)["drop"] for row in report.read_text().splitlines()], [True, False])
            responses.write_text(json.dumps(rows[0]))
            with self.assertRaisesRegex(ValueError, "one A response"):
                precheck(questions, responses, report)


if __name__ == "__main__":
    unittest.main()
