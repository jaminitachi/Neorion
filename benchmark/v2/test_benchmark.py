from pathlib import Path
from tempfile import TemporaryDirectory
import unittest

from benchmark import choose_detail, grade


class BenchmarkTests(unittest.TestCase):
    def test_grades_last_list_and_reports_format_separately(self):
        response = 'First {"answer":["wrong"]}\n```json\n{"answer":["./papermark/pages\\\\api.ts","post   /api/x"]}\n```'
        result = grade(response, ["pages/api.ts", "POST /api/x"], "mfts/papermark")
        self.assertTrue(result["content_exact"])
        self.assertFalse(result["format_ok"])
        self.assertTrue(result["ambiguous"])
        self.assertEqual(result["f1"], 1)

    def test_partial_and_malformed_json(self):
        self.assertEqual(grade('{"answer":["A","A"]}', ["A", "B"], "repo")["f1"], 2 / 3)
        self.assertTrue(grade('{"answer":["A"]}', ["A"], "repo")["format_ok"])
        self.assertFalse(grade('{"answer":[null]}', ["A"], "repo")["content_exact"])

    def test_selection_prioritizes_an_explicit_area(self):
        with TemporaryDirectory() as root:
            root = Path(root)
            graph = root / ".neorion/graph"
            graph.mkdir(parents=True)
            (graph / "one.md").write_text("<!-- Generated by Neorion -->\n# components/chat\n")
            (graph / "two.md").write_text("<!-- Generated by Neorion -->\n# pages\n\nuseStream")
            self.assertEqual(choose_detail("Which components/chat/ files use useStream?", root)[0],
                             ".neorion/graph/one.md")


if __name__ == "__main__":
    unittest.main()
