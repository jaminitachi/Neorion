import { Tiktoken } from 'js-tiktoken/lite';
import ranks from 'js-tiktoken/ranks/o200k_base';
import { createHash } from 'crypto';
import { posix } from 'path';
import type { CodebaseGraph, RouteNode } from '../types/GraphTypes';

export const DETAIL_DIRECTORY = '.neorion/graph';
export const DETAIL_MARKER = '<!-- Generated by Neorion -->\n';
const DETAIL_BUDGET = 3000;
let tokenizer: Tiktoken | undefined;
const count = (text: string) => (tokenizer ??= new Tiktoken(ranks)).encode(text, [], []).length;

function add<K, V>(map: Map<K, V[]>, key: K, value: V) {
  const items = map.get(key);
  if (items) items.push(value);
  else map.set(key, [value]);
}

function areaOf(file: string): string {
  const directories = file.split('/').slice(0, -1);
  return directories.slice(0, directories[0] === 'src' ? 3 : 2).join('/') || '.';
}

function routeLabel(route: RouteNode, names: Map<string, string>) {
  const file = posix.basename(route.file);
  const app = /^(?:src\/)?app\//.test(route.file);
  const relative = route.file.replace(/^(?:src\/)?(?:app|pages)\//, '');
  const inferred = '/' + (app
    ? posix.dirname(relative).split('/').filter(part => part !== '.' && !part.startsWith('@') && !/^\([^()]+\)$/.test(part)).join('/')
    : relative.replace(/\.[^.]+$/, '').replace(/(?:^|\/)index$/, ''));
  const path = route.path === inferred ? '' : ` → ${route.path}`;
  const type = route.type === 'layout' ? '(L)' : route.type === 'api'
    ? `[${route.methods?.join(' ').replace(/^ALL$/, '*') || '?'}]`
    : route.type === 'page' ? '' : `(${route.type})`;
  return file + type + (route.isClient ? '(c)' : '') +
    (route.componentId ? '=' + (names.get(route.componentId) ?? route.componentId.slice(4)) : '') + path;
}

function routeTree(routes: RouteNode[], names: Map<string, string>) {
  interface Branch { children: Map<string, Branch>; files: string[] }
  const trunk: Branch = { children: new Map(), files: [] };
  for (const route of routes) {
    let branch = trunk;
    for (const part of posix.dirname(route.file).split('/')) {
      if (!branch.children.has(part)) branch.children.set(part, { children: new Map(), files: [] });
      branch = branch.children.get(part)!;
    }
    branch.files.push(routeLabel(route, names));
  }
  const lines: string[] = [];
  const visit = (name: string, branch: Branch, indent: string) => {
    while (!branch.files.length && branch.children.size === 1) {
      const [child, next] = branch.children.entries().next().value!;
      name += '/' + child;
      branch = next;
    }
    const labels = branch.files.sort();
    lines.push(indent + name + (labels.length ? '  ' + labels.slice(0, 8).join('  ') : ''));
    for (let i = 8; i < labels.length; i += 8) {
      lines.push(indent + '  .  ' + labels.slice(i, i + 8).join('  '));
    }
    for (const [child, next] of [...branch.children].sort(([a], [b]) => a.localeCompare(b))) {
      visit(child, next, indent + '  ');
    }
  };
  for (const [name, branch] of trunk.children) visit(name, branch, '');
  return lines;
}

export class MarkdownSerializer {
  public serialize(graph: CodebaseGraph, fileList: string) {
    const budget = Math.min(6000, Math.max(1500, Math.floor(count(fileList) / 4)));
    const details = new Map<string, string>();
    const index: string[] = [];
    const byArea = new Map<string, Map<string, string[]>>();
    const names = new Map(graph.components.map(component => [component.id, component.name]));
    for (const hook of graph.hooks) names.set(hook.id, hook.name);
    const frequencies = new Map<string, number>();
    for (const name of names.values()) frequencies.set(name, (frequencies.get(name) ?? 0) + 1);
    const label = (id: string) => {
      const name = names.get(id);
      return name && frequencies.get(name) === 1 ? name : id.slice(id.indexOf(':') + 1);
    };
    const fileLines = (file: string) => {
      const area = areaOf(file);
      if (!byArea.has(area)) byArea.set(area, new Map());
      const files = byArea.get(area)!;
      if (!files.has(file)) files.set(file, []);
      return files.get(file)!;
    };

    const actions: string[] = [];
    for (const action of [...graph.actions].sort()) {
      const id = label(action);
      actions.push(id);
      fileLines(id.slice(0, id.lastIndexOf('#'))).push('action ' + id.slice(id.lastIndexOf('#') + 1));
    }

    const componentFiles = new Map(graph.components.map(component => [component.id, component.path]));
    const outgoing = new Map<string, Map<string, Map<string, Set<string>>>>();
    const sourceCounts = new Map<string, number>();
    for (const file of componentFiles.values()) sourceCounts.set(file, (sourceCounts.get(file) ?? 0) + 1);
    const omitted = new Map<string, Set<string>>();
    const actionCalls = new Map<string, Set<string>>();
    for (const { from, to, type } of graph.edges) {
      const file = componentFiles.get(from) ?? from.slice('file:'.length);
      if (type === 'uses-action') {
        if (!actionCalls.has(file)) actionCalls.set(file, new Set());
        actionCalls.get(file)!.add(label(to));
      }
      const target = componentFiles.get(to);
      if (target && /(?:^|\/)(?:components\/ui|components\/(?:shared\/)?icons|icons)\//.test(target)) {
        if (!omitted.has(file)) omitted.set(file, new Set());
        omitted.get(file)!.add(to);
        continue;
      }
      if (!outgoing.has(file)) outgoing.set(file, new Map());
      const sources = outgoing.get(file)!;
      const source = (sourceCounts.get(file) ?? 0) > 1 || (from.startsWith('file:') && sourceCounts.has(file))
        ? names.get(from) ?? 'module' : '';
      if (!sources.has(source)) sources.set(source, new Map());
      const targets = sources.get(source)!;
      if (!targets.has(to)) targets.set(to, new Set());
      const types = targets.get(to)!;
      types.add(type);
    }

    for (const [file, { hooks }] of graph.fileHooks) {
      fileLines(file).push('h:' + hooks.map(label).join(','));
    }
    const clientFiles = new Set([
      ...graph.components.filter(component => component.isClient).map(component => component.path),
      ...[...graph.fileHooks].filter(([, metadata]) => metadata.isClient).map(([file]) => file)
    ]);
    for (const component of graph.components) {
      const { path, name, props, hooks, description } = component;
      fileLines(path).push(name +
        (props.length ? '(' + props.join(',') + ')' : '') +
        (hooks.length ? ' h:' + hooks.map(label).join(',') : '') +
        (description ? ' — ' + description.trim().split(/\r?\n/, 1)[0] : ''));
    }
    const projectHooks = new Map<string, string[]>();
    for (const hook of graph.hooks) {
      if (hook.path) add(projectHooks, hook.path, hook.name);
    }
    for (const [file, hooks] of projectHooks) fileLines(file).push('defines hooks ' + hooks.sort().join(','));
    for (const route of graph.routes) fileLines(route.file).push('route ' + routeLabel(route, names));
    for (const [file, sources] of outgoing) {
      for (const [source, targets] of sources) {
        fileLines(file).push((source ? source + ' ' : '') + '> ' + [...targets].map(([id, types]) => label(id) +
          (types.has('uses-action') ? '[action]' : types.has('imports') ? (types.has('renders') ? '' : '[import]') : '[render]'))
          .sort().join(' '));
      }
    }
    for (const [file, targets] of omitted) fileLines(file).push(`+${targets.size} UI/icon targets`);

    const publish = (area: string, rows: string[], fileCount: number) => {
      const encoded = (area === 'Dependencies' && fileCount === 0 ? '+dependencies' : encodeURIComponent(area)).replace(/[!'()*]/g, c => '%' + c.charCodeAt(0).toString(16));
      const stem = encoded.length > 210 ? encoded.slice(0, 140) + '~' +
        createHash('sha256').update(area).digest('hex') : encoded;
      const heading = DETAIL_MARKER + `# ${area}\n\n~~~text\n`;
      const footer = '~~~\n';
      const parts: string[] = [];
      let entries: { text: string; directory: string }[] = [];
      const headingSize = count(heading);
      let size = headingSize;
      const flush = () => {
        if (!entries.length) return;
        const content = heading + entries.map(entry => entry.text).join('') + footer;
        if (count(content) > DETAIL_BUDGET) throw new Error(`Graph detail exceeded its token budget for ${area}`);
        parts.push(content);
        entries = [];
        size = headingSize;
      };
      let directory = '';
      for (const row of rows) {
        if (row.startsWith('\n')) {
          directory = row;
          continue;
        }
        let rest = row;
        while (rest) {
          const prefix = !entries.length || entries[entries.length - 1]?.directory !== directory ? directory : '';
          let length = rest.length;
          if (size + count(prefix + rest) > DETAIL_BUDGET - 16 && entries.length) {
            flush();
            continue;
          }
          while (length && size + count(prefix + rest.slice(0, length)) > DETAIL_BUDGET - 16) {
            length = Math.floor(length / 2);
          }
          if (!length) throw new Error(`Graph directory path exceeds the detail budget in ${area}`);
          if (length < rest.length) {
            const boundary = rest.lastIndexOf(' ', length);
            if (boundary > length / 2) length = boundary + 1;
          }
          const entry = prefix + rest.slice(0, length);
          entries.push({ text: entry.endsWith('\n') ? entry : entry + '\n', directory });
          size += count(entry);
          rest = rest.slice(length);
          if (rest) flush();
        }
      }
      flush();
      const links = parts.map((part, i) => {
        const filename = stem + (i ? `+${i + 1}` : '') + '.md';
        details.set(filename, part);
        return `[${i ? i + 1 : 'detail'}](${DETAIL_DIRECTORY}/${encodeURIComponent(filename)})`;
      });
      if (links.length) index.push(`- ${area} (${fileCount}) ${links.join(' ')}`);
    };

    for (const [area, files] of [...byArea].sort(([a], [b]) => a.localeCompare(b))) {
      let directory: string | undefined;
      const rows: string[] = [];
      for (const [file, items] of [...files].sort(([a], [b]) =>
        posix.dirname(a).localeCompare(posix.dirname(b)) || a.localeCompare(b))) {
        const parent = posix.dirname(file);
        if (parent !== directory) {
          directory = parent;
          rows.push(`\n${directory}/\n`);
        }
        rows.push(`  ${posix.basename(file)}${clientFiles.has(file) ? ' (c)' : ''}: ${items.join(' | ')}\n`);
      }
      publish(area, rows, files.size);
    }

    publish('Dependencies', [
      ...graph.libraries.map(({ name, version }) => `${name} ${version}\n`).sort(),
      ...graph.devDependencies.map(name => `dev ${name}\n`)
    ], 0);

    const section = (heading: string, rows: readonly string[]) => rows.length
      ? `\n## ${heading}\n\n${rows.join('\n')}\n` : '';
    const intro = `# ${graph.metadata.name.replace(/\s+/g, ' ').slice(0, 120)} architecture (${graph.metadata.router} router)\n\n` +
      `Start here, then open relevant area links below or browse [all details](${DETAIL_DIRECTORY}/). ` +
      'Detail headings name source areas. Numbered parts continue the same area.\n' +
      'Details list files under directory prefixes. Edges are grouped by source file. ' +
      'Unmarked targets render and import. [render], [import] and [action] mark other relationships. UI/icon targets are counted.\n' +
      'Unmarked files use the server default. (c) marks a client boundary, (L) a layout wrapping pages below it, and [*] unknown Pages API methods.\n' +
      'Routes follow the tree. Drop App Router groups and slots, or the Pages filename extension and trailing index. A dot continues the parent route row. Explicit URL overrides follow →.\n';
    const sections = [
      ['Routes', routeTree(graph.routes, names), true],
      ['Server actions', [...actions, ...[...actionCalls].map(([file, targets]) => `${file} > ${[...targets].sort().join(' ')}`).sort()], true],
      ['Areas', index, false],
      ['Project hooks', [...projectHooks].map(([file, hooks]) => `${file}: ${hooks.join(',')}`).sort(), true]
    ] as const;
    const lengths = sections.map(([, rows]) => rows.length);
    const render = () => {
      const omitted = sections.filter(([, rows], i) => lengths[i] < rows.length).map(([name]) => name);
      return (omitted.length ? `Overview abbreviates ${omitted.join(', ')}. See area details.\n\n` : '') + intro +
        sections.map(([name, rows, tree], i) => {
          const visible = rows.slice(0, lengths[i]);
          return section(name, tree && visible.length ? ['~~~text', ...visible, '~~~'] : visible);
        }).join('');
    };
    let overview = render();
    for (const i of [3, 1, 2, 0]) {
      if (count(overview) <= budget) break;
      // Keep entry points into the details even if the route tree alone exceeds the budget.
      let low = i === 2 ? Math.min(3, lengths[i]) : 0;
      let high = lengths[i];
      while (low < high) {
        lengths[i] = Math.ceil((low + high) / 2);
        if (count(render()) <= budget) low = lengths[i];
        else high = lengths[i] - 1;
      }
      lengths[i] = low;
      overview = render();
    }
    if (count(overview) > budget) throw new Error('Graph overview exceeded its token budget');
    return { overview, details };
  }
}
